<#
.SYNOPSIS
  Pull the transcript of a YouTube video from its published caption track.

.DESCRIPTION
  No API keys, no download, no speech-to-text model, no LLM calls. YouTube has already
  transcribed the video: every video with speech carries a caption track, either uploaded
  by the channel or generated by YouTube's own ASR. Both are public and both are fetchable.

  Two layers, because one is not enough:

    INNERTUBE : POST to the player endpoint the YouTube clients themselves use. Returns the
                caption track list as JSON. Several client contexts are tried because any
                one of them can be refused on a given day.
    PAGE      : fall back to scraping ytInitialPlayerResponse out of the watch page HTML.

  Either layer yields a timed-text URL. That is fetched as json3 (falling back to YouTube's
  older XML) and rendered as plain text, timestamped lines, SRT, VTT or JSON.

.PARAMETER Url
  One or more video URLs or bare 11-character video IDs. watch, youtu.be, shorts, embed
  and live URLs are all accepted.

.PARAMETER InputFile
  Text or CSV file with one video URL or ID per line. Anything on the line that is not a
  recognisable video reference is ignored, so pasted lists with extra columns still work.

.PARAMETER Language
  Preferred caption language code. Defaults to en. Manual captions in that language win,
  then auto-generated ones, then anything else the video has.

.PARAMETER Translate
  Ask YouTube to machine-translate the chosen track into this language code.

.PARAMETER Format
  Text (flowing paragraphs, default), Lines, Timestamps, Srt, Vtt or Json.

.PARAMETER OutputPath
  File to write for a single video, or a directory when several are requested. Without it
  the transcript goes to stdout so it can be piped or redirected.

.PARAMETER ListTracks
  Report the caption tracks the video actually has and stop. Use this when the language
  you asked for came back empty.

.PARAMETER NoAuto
  Refuse auto-generated captions. Only human-authored tracks are accepted.

.EXAMPLE
  .\yt-transcript.ps1 https://www.youtube.com/watch?v=dQw4w9WgXcQ

.EXAMPLE
  .\yt-transcript.ps1 dQw4w9WgXcQ -Format Srt -OutputPath subs.srt

.EXAMPLE
  .\yt-transcript.ps1 -InputFile videos.txt -OutputPath .\transcripts -Format Timestamps

.NOTES
  Read-only. It requests the same public caption data the YouTube web player requests when
  you press CC. It does not download audio or video, does not sign in, and does not touch
  anything behind a paywall or an age gate.

  YouTube changes these endpoints without notice. When every layer fails at once, that is
  the usual cause rather than anything about the specific video.
#>
[CmdletBinding(DefaultParameterSetName = 'Direct')]
param(
  [Parameter(ParameterSetName = 'Direct', Mandatory = $true, Position = 0)]
  [string[]]$Url,

  [Parameter(ParameterSetName = 'File', Mandatory = $true)]
  [string]$InputFile,

  [string]$Language = 'en',
  [string]$Translate,

  [ValidateSet('Text', 'Lines', 'Timestamps', 'Srt', 'Vtt', 'Json')]
  [string]$Format = 'Text',

  [string]$OutputPath,

  # Report what caption tracks exist and stop.
  [switch]$ListTracks,

  # Reject YouTube's ASR captions. Human-authored tracks only.
  [switch]$NoAuto,

  # Seconds to wait between videos. Be polite on long lists.
  [int]$DelaySeconds = 0
)

